bookings = []
booking_ids = set()
next_id = 1001


# 2. View all routes
def view_routes():
    print("\nAVAILABLE BUS ROUTES")

    for number, route in enumerate(routes, start=1):
        status = "Fully Booked" if route["available_seats"] == 0 else "Available"

